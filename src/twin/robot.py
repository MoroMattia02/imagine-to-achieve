"""UR5 kinematic model of the twin (milestone T1: numpy forward kinematics).

The constants are those of the repo FK ``ur5_joint_actions_to_eef_states``
(third_party/rlinf_runtime/rlinf/envs/world_model/eef_pose_adapter.py:461): the original UR5,
not the UR5e (lab request 5 is still open). That function produced Ctrl-World's conditioning
states, so the twin must reproduce it exactly; tests/test_twin_fk.py checks this against a
reference table generated from the repo function.
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

# Standard DH, one row per joint: (a [m], d [m], alpha [rad]); T_{i-1,i} = Rz(q) Tz(d) Tx(a) Rx(alpha).
UR5_DH: tuple[tuple[float, float, float], ...] = (
    (0.0, 0.089159, math.pi / 2),
    (-0.425, 0.0, 0.0),
    (-0.39225, 0.0, 0.0),
    (0.0, 0.10915, math.pi / 2),
    (0.0, 0.09465, -math.pi / 2),
    (0.0, 0.0823, 0.0),
)

# TCP relative to the flange (frame 6): 0.18 m along z, no rotation (repo default).
TCP_OFFSET: tuple[float, float, float] = (0.0, 0.0, 0.18)

# Joint limits [rad], shape (6, 2). Original UR5: +-2*pi on every joint (check with the lab).
JOINT_LIMITS = np.array([[-2.0 * math.pi, 2.0 * math.pi]] * 6)

JOINT_NAMES = ("shoulder_pan", "shoulder_lift", "elbow", "wrist_1", "wrist_2", "wrist_3")
LINK_NAMES = (
    "shoulder_link",
    "upper_arm_link",
    "forearm_link",
    "wrist_1_link",
    "wrist_2_link",
    "wrist_3_link",
)

# Visual/inertial placeholders, not used by kinematics. Masses: nominal UR5 link masses [kg]
# (check against UR's published dynamics); capsule radii [m] are rough guesses (check). The
# controller (T2) and contact (T3) milestones revisit both.
_LINK_MASSES = (3.7, 8.393, 2.275, 1.219, 1.219, 0.1879)
_LINK_RADII = (0.06, 0.054, 0.045, 0.04, 0.04, 0.035)

UR5_ASSET_PATH = Path(__file__).resolve().parent / "assets" / "ur5.xml"


def dh_transform(a: float, d: float, alpha: float, theta: np.ndarray) -> np.ndarray:
    """Standard DH link transform for joint angles ``theta`` of shape ``(...)``; returns ``(..., 4, 4)``."""
    theta = np.asarray(theta, dtype=np.float64)
    ct, st = np.cos(theta), np.sin(theta)
    ca, sa = math.cos(alpha), math.sin(alpha)
    T = np.zeros(theta.shape + (4, 4))
    T[..., 0, 0] = ct
    T[..., 0, 1] = -st * ca
    T[..., 0, 2] = st * sa
    T[..., 0, 3] = a * ct
    T[..., 1, 0] = st
    T[..., 1, 1] = ct * ca
    T[..., 1, 2] = -ct * sa
    T[..., 1, 3] = a * st
    T[..., 2, 1] = sa
    T[..., 2, 2] = ca
    T[..., 2, 3] = d
    T[..., 3, 3] = 1.0
    return T


def fk(q: np.ndarray, *, tcp: bool = True) -> np.ndarray:
    """Forward kinematics ``T_BE(q)``: base frame B to TCP frame E (or flange if ``tcp=False``).

    Args:
        q: joint angles [rad], shape ``(..., 6)``.

    Returns:
        ``(..., 4, 4)`` homogeneous transforms (rotation as a matrix, no axis-angle).
    """
    q = np.asarray(q, dtype=np.float64)
    if q.shape[-1:] != (6,):
        raise ValueError(f"q must have shape (..., 6), got {q.shape}")
    T = np.broadcast_to(np.eye(4), q.shape[:-1] + (4, 4))
    for j, (a, d, alpha) in enumerate(UR5_DH):
        T = T @ dh_transform(a, d, alpha, q[..., j])
    if tcp:
        T_6E = np.eye(4)
        T_6E[:3, 3] = TCP_OFFSET
        T = T @ T_6E
    return T


# --- MuJoCo model ----------------------------------------------------------------------------


def _num(x: float) -> str:
    """Full-precision float for MJCF (repr round-trips float64)."""
    return repr(float(x))


def _vec(*xs: float) -> str:
    return " ".join(_num(x) for x in xs)


def ur5_mjcf_xml() -> str:
    """MJCF of the UR5 arm, generated from ``UR5_DH`` and ``TCP_OFFSET`` (no mujoco import).

    The DH chain is written as ``T_BE = prod_i [Rz(q_i) F_i] T_tcp`` with the constant
    ``F_i = Tz(d_i) Tx(a_i) Rx(alpha_i)``. Body ``i`` sits in body ``i-1`` at pose ``F_{i-1}``
    (``pos = (a, 0, d)``, ``quat`` of ``Rx(alpha)``; identity for the first body), so every body
    frame lies on its own joint axis: a hinge about +z at the body origin, with ``qpos = q``
    (the repo uses no joint offsets). Sites: ``flange`` at ``F_6``, ``tcp`` at ``F_6 T_tcp``.
    """
    lines = [
        "<!-- Generated by scripts/make_twin_ur5_mjcf.py from twin.robot.UR5_DH. Do not edit. -->",
        '<mujoco model="ur5_dh">',
        '  <compiler angle="radian" autolimits="true"/>',
        "  <default>",
        '    <geom contype="0" conaffinity="0" group="1" rgba="0.7 0.7 0.75 1"/>',
        "  </default>",
        "  <worldbody>",
        '    <body name="base">',
        '      <geom name="base_geom" type="cylinder" size="0.075 0.04" pos="0 0 -0.04"/>',
    ]
    indent = "      "
    parent_F = (0.0, 0.0, 0.0)  # (a, d, alpha) of the previous link; identity for body 1
    for i, ((a, d, alpha), joint, link) in enumerate(zip(UR5_DH, JOINT_NAMES, LINK_NAMES)):
        pa, pd, palpha = parent_F
        quat = _vec(math.cos(palpha / 2), math.sin(palpha / 2), 0.0, 0.0)
        lines.append(f'{indent}<body name="{link}" pos="{_vec(pa, 0.0, pd)}" quat="{quat}">')
        inner = indent + "  "
        lines.append(
            f'{inner}<joint name="{joint}" type="hinge" axis="0 0 1" '
            f'range="{_vec(*JOINT_LIMITS[i])}"/>'
        )
        lines.append(
            f'{inner}<geom name="{link}_geom" type="capsule" size="{_num(_LINK_RADII[i])}" '
            f'fromto="0 0 0 {_vec(a, 0.0, d)}" mass="{_num(_LINK_MASSES[i])}"/>'
        )
        parent_F = (a, d, alpha)
        indent = inner
    a6, d6, alpha6 = UR5_DH[-1]
    assert alpha6 == 0.0 and a6 == 0.0, "sites below assume F_6 is a pure z translation"
    lines.append(f'{indent}<site name="flange" pos="{_vec(0.0, 0.0, d6)}" size="0.01"/>')
    tx, ty, tz = TCP_OFFSET
    lines.append(f'{indent}<site name="tcp" pos="{_vec(tx, ty, d6 + tz)}" size="0.01"/>')
    for _ in range(len(UR5_DH)):
        indent = indent[:-2]
        lines.append(f"{indent}</body>")
    lines += ["    </body>", "  </worldbody>", "</mujoco>", ""]
    return "\n".join(lines)


def load_ur5_model():
    """Compile the generated UR5 MJCF into a ``mujoco.MjModel`` (requires mujoco)."""
    import mujoco

    return mujoco.MjModel.from_xml_string(ur5_mjcf_xml())
